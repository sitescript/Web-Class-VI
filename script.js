function updatetimedate() {

    let sekarang = new Date();

    let jam = String(sekarang.getHours()).padStart(2, "0");
    let menit = String(sekarang.getMinutes()).padStart(2, "0");
    let detik = String(sekarang.getSeconds()).padStart(2, "0");

    jamdigital.textContent = jam + ":" + menit + ":" + detik;
    let tanggal = sekarang.getDate();
    let bulan = sekarang.getMonth();
    let tahun = sekarang.getFullYear();

    let namabulan = [
        "Januari",
        "Februari",
        "Maret",
        "April",
        "Mei",
        "Juni",
        "Juli",
        "Agustus",
        "September",
        "Oktober",
        "November",
        "Desember",
    ];

    tanggaldigital.textContent = tanggal + " " + namabulan[bulan] + " " + tahun;
}
