// Intro sebelum masuk ke konten utama
const introscreen = document.getElementById("intro-screen");
const introenter = document.getElementById("intro-enter");
const maincontent = document.getElementById("main-content");

introenter.focus({ preventScroll: true });

introenter.addEventListener("click", function () {
    introenter.disabled = true;
    introscreen.classList.add("is-loading");

    const introloader = document.getElementById("intro-loader");
    const introprogress = document.getElementById("intro-progress");
    const introprogressbar = document.getElementById("intro-progress-bar");
    const introprogresstext = document.getElementById("intro-progress-text");
    const introlabel = document.getElementById("intro-loading-text");
    const intronote = document.getElementById("intro-note");

    introloader.hidden = false;
    introprogress.focus({ preventScroll: true });
    intronote.textContent = "Tunggu sebentar, Akses menuju server sedang dibuka.";

    let progress = 0;
    const loadingInterval = window.setInterval(function () {
        progress = Math.min(progress + 1.2, 100);
        const roundedProgress = Math.floor(progress);

        introprogressbar.style.width = `${progress}%`;
        introprogresstext.textContent = `${roundedProgress}%`;
        introprogress.setAttribute("aria-valuenow", String(roundedProgress));

        if (progress < 35) {
            introlabel.textContent = "Menyiapkan Variabel...";
        } else if (progress < 72) {
            introlabel.textContent = "Mengumpulkan Data Variabel...";
        } else if (progress < 100) {
            introlabel.textContent = "Mengakses Server...";
        } else {
            window.clearInterval(loadingInterval);
            introlabel.textContent = "Siap, selamat datang!";

            window.setTimeout(function () {
                introscreen.setAttribute("aria-hidden", "true");
                introscreen.classList.add("is-leaving");

                const reducedmotion = window.matchMedia(
                    "(prefers-reduced-motion: reduce)"
                ).matches;

                window.setTimeout(function () {
                    introscreen.hidden = true;
                    document.body.classList.remove("intro-active");
                    maincontent.focus({ preventScroll: true });
                }, reducedmotion ? 0 : 550);
            }, 240);
        }
    }, 18);
});